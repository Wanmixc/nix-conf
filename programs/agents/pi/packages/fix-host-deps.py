#!/usr/bin/env python3
"""Move host-provided packages out of dependencies in installed Pi extensions.

Pi aliases these packages to its own copies when loading extensions, so an
installed copy is never imported. Pi warns at startup when an extension
declares one under `dependencies` instead of `peerDependencies` with a "*"
range, because such a copy can bypass the extension loader and create
duplicate runtime modules.

Currently this applies to pi-web-access, which lists typebox under
dependencies while Pi provides it. Removing the entry from the lockfile is not
possible: the lockfile is generated by `npm ci` from upstream manifests, so the
installed manifest is patched after installation instead.

Usage: fix-host-deps.py <node_modules directory>

Only top-level extension packages are patched. Host packages that Pi aliases to
itself (such as @earendil-works/pi-coding-agent) are skipped: their manifests
are never scanned for this warning.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Must match HOST_PROVIDED_EXTENSION_PACKAGES in Pi's resource-loader.
HOST_PROVIDED = {
    "@earendil-works/pi-agent-core",
    "@earendil-works/pi-ai",
    "@earendil-works/pi-coding-agent",
    "@earendil-works/pi-tui",
    "@mariozechner/pi-agent-core",
    "@mariozechner/pi-ai",
    "@mariozechner/pi-coding-agent",
    "@mariozechner/pi-tui",
    "@sinclair/typebox",
    "typebox",
}


def is_host_package(name: str) -> bool:
    return name in HOST_PROVIDED


def fix_manifest(manifest_path: Path) -> list[str]:
    """Move host-provided dependencies to peerDependencies; return the names."""
    manifest = json.loads(manifest_path.read_text())

    # Skip host packages themselves; only extension manifests are scanned.
    if is_host_package(manifest.get("name", "")):
        return []

    dependencies = manifest.get("dependencies")
    if not isinstance(dependencies, dict):
        return []

    moved = sorted(name for name in dependencies if name in HOST_PROVIDED)
    if not moved:
        return []

    peers = manifest.get("peerDependencies")
    if not isinstance(peers, dict):
        peers = {}
    for name in moved:
        del dependencies[name]
        peers[name] = "*"
    manifest["peerDependencies"] = peers

    # Keep peerDependenciesMeta consistent if the manifest declared one.
    peers_meta = manifest.get("peerDependenciesMeta")
    if isinstance(peers_meta, dict):
        for name in moved:
            peers_meta.pop(name, None)

    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    return moved


def main() -> int:
    if len(sys.argv) != 2:
        print(f"usage: {Path(sys.argv[0]).name} <node_modules directory>", file=sys.stderr)
        return 2

    node_modules = Path(sys.argv[1])
    if not node_modules.is_dir():
        print(f"error: not a directory: {node_modules}", file=sys.stderr)
        return 1

    changed = 0
    for manifest_path in sorted(node_modules.glob("*/package.json")) + sorted(
        node_modules.glob("@*/*/package.json")
    ):
        moved = fix_manifest(manifest_path)
        if moved:
            changed += 1
            print(f"{manifest_path}: moved to peerDependencies: {', '.join(moved)}")

    if changed == 0:
        print("no host-provided dependencies found to fix")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
